"""Generate app/lib/catalog/catalog_schemas.g.dart from the Siargao catalog.

For each component the output holds a const map with only the
component-specific schema: description, properties (without `component`) and
the required list (without `component`). genui adds the `component`
discriminator itself (CatalogItem.dataSchema) and wraps the map with the
ComponentCommon refs when it builds Catalog.fullSchema. The app builds each
schema with `Schema.fromMap(...)`.

Refs to the spec's common types stay absolute
(https://a2ui.org/specification/v0_9/common_types.json#/$defs/...), which is
how genui's own A2uiSchemas helpers write them.

Usage (from projects/siargao-genui):
    catalog/.venv/bin/python catalog/tools/gen_dart.py           # write the file
    catalog/.venv/bin/python catalog/tools/gen_dart.py --check   # exit 1 if stale

The output is run through `dart format`. Set DART to the dart binary if it is
not at ~/fvm/versions/3.47.5/bin/dart or on PATH.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

CATALOG_DIR = Path(__file__).resolve().parents[1]
PROJECT_DIR = CATALOG_DIR.parent
CATALOG_PATH = CATALOG_DIR / "siargao_catalog.json"
IMAGES_PATH = CATALOG_DIR / "images.json"
OUTPUT_PATH = PROJECT_DIR / "app" / "lib" / "catalog" / "catalog_schemas.g.dart"
COMMAND = "catalog/.venv/bin/python catalog/tools/gen_dart.py"
DEFAULT_DART = Path.home() / "fvm" / "versions" / "3.47.5" / "bin" / "dart"


def find_dart() -> str | None:
    for candidate in (os.environ.get("DART"), str(DEFAULT_DART), shutil.which("dart")):
        if candidate and Path(candidate).is_file():
            return candidate
    return None


def component_schema(name: str, spec: dict[str, Any]) -> dict[str, Any]:
    """Extract the component-specific part of a catalog component."""
    own = [
        part
        for part in spec["allOf"]
        if isinstance(part, dict) and part.get("properties", {}).get("component", {}).get("const") == name
    ]
    if len(own) != 1:
        raise ValueError(f"{name}: expected one allOf entry with component const {name!r}")
    props = {k: v for k, v in own[0]["properties"].items() if k != "component"}
    required = [r for r in own[0].get("required", []) if r != "component"]
    _reject_local_refs(props, name)
    out: dict[str, Any] = {"type": "object"}
    if "description" in spec:
        out["description"] = spec["description"]
    out["properties"] = props
    out["required"] = required
    return out


def _reject_local_refs(value: Any, where: str) -> None:
    """Local refs like #/$defs/X would not resolve inside genui's fullSchema."""
    if isinstance(value, dict):
        ref = value.get("$ref")
        if isinstance(ref, str) and ref.startswith("#"):
            raise ValueError(f"{where}: local $ref {ref!r} is not allowed in component properties")
        for k, v in value.items():
            _reject_local_refs(v, f"{where}.{k}")
    elif isinstance(value, list):
        for i, v in enumerate(value):
            _reject_local_refs(v, f"{where}[{i}]")


def dart_string(s: str) -> str:
    quote = '"' if "'" in s and '"' not in s else "'"
    if "$" in s and "\\" not in s and quote not in s and "\n" not in s:
        return f"r{quote}{s}{quote}"
    escaped = s.replace("\\", "\\\\").replace("$", "\\$").replace("\n", "\\n").replace(quote, "\\" + quote)
    return f"{quote}{escaped}{quote}"


def dart_value(value: Any) -> str:
    if isinstance(value, dict):
        if not value:
            return "<String, Object?>{}"
        items = ", ".join(f"{dart_string(k)}: {dart_value(v)}" for k, v in value.items())
        return f"<String, Object?>{{{items},}}"
    if isinstance(value, list):
        if not value:
            return "<Object?>[]"
        items = ", ".join(dart_value(v) for v in value)
        return f"<Object?>[{items},]"
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "null"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return repr(value)
    if isinstance(value, str):
        return dart_string(value)
    raise TypeError(f"cannot convert {type(value).__name__} to Dart")


def lower_camel(name: str) -> str:
    return name[0].lower() + name[1:]


def generate_source() -> str:
    with CATALOG_PATH.open(encoding="utf-8") as f:
        catalog = json.load(f)
    with IMAGES_PATH.open(encoding="utf-8") as f:
        images = json.load(f)["images"]

    lines = [
        "// GENERATED CODE. DO NOT MODIFY BY HAND.",
        f"// Generated by `{COMMAND}` (run from projects/siargao-genui)",
        "// from catalog/siargao_catalog.json and catalog/images.json.",
        "//",
        "// Each map is the component-specific data schema for a genui CatalogItem:",
        "// build it with Schema.fromMap(...). genui adds the `component` property.",
        "",
        "// ignore_for_file: type=lint",
        "",
        "/// The A2UI catalogId of the Siargao catalog.",
        f"const String siargaoCatalogId = {dart_string(catalog['catalogId'])};",
        "",
        "/// Image keys components may use. Assets live at assets/img/<key>.jpg|png|webp.",
        f"const List<String> siargaoImageKeys = <String>[{', '.join(dart_string(i['key']) for i in images)},];",
        "",
        "/// Alt text for each image key.",
        "const Map<String, String> siargaoImageAlt = <String, String>{"
        + ", ".join(f"{dart_string(i['key'])}: {dart_string(i['alt'])}" for i in images)
        + ",};",
        "",
    ]
    names = list(catalog["components"])
    for name in names:
        schema = component_schema(name, catalog["components"][name])
        lines.append(f"/// Data schema for the `{name}` component.")
        lines.append(f"const Map<String, Object?> {lower_camel(name)}Schema = {dart_value(schema)};")
        lines.append("")
    lines.append("/// Every component name mapped to its data schema, in catalog order.")
    lines.append(
        "const Map<String, Map<String, Object?>> siargaoComponentSchemas = <String, Map<String, Object?>>{"
        + ", ".join(f"{dart_string(n)}: {lower_camel(n)}Schema" for n in names)
        + ",};"
    )
    return "\n".join(lines) + "\n"


def dart_format(source: str, dart: str) -> str:
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "catalog_schemas.g.dart"
        path.write_text(source, encoding="utf-8")
        subprocess.run([dart, "format", "--output=write", str(path)], check=True, capture_output=True)
        return path.read_text(encoding="utf-8")


def render() -> str:
    dart = find_dart()
    if dart is None:
        raise RuntimeError("dart not found; set DART to the dart binary")
    return dart_format(generate_source(), dart)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the Dart catalog schemas for the app.")
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is missing or out of date")
    args = parser.parse_args(argv)

    output = render()
    if args.check:
        current = OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.exists() else None
        if current != output:
            print(f"{OUTPUT_PATH.relative_to(PROJECT_DIR)} is out of date. Run: {COMMAND}")
            return 1
        print(f"{OUTPUT_PATH.relative_to(PROJECT_DIR)} is up to date.")
        return 0
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(output, encoding="utf-8")
    print(f"wrote {OUTPUT_PATH.relative_to(PROJECT_DIR)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
